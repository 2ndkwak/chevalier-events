def write_config(data):
    os.makedirs(INST_DIR, exist_ok=True)
    secret = secrets.token_hex(32)
    lines = [
        "# Chevalier Events - instance configuration",
        "# Generated by Setup Wizard. Edit here to change settings.",
        "",
        "SECRET_KEY = " + repr(secret),
        "",
        "ANTHROPIC_API_KEY = " + repr(data["anthropic_key"]),
        "",
        'MAIL_SERVER         = "smtp.gmail.com"',
        "MAIL_PORT           = 587",
        "MAIL_USE_TLS        = True",
        "MAIL_USERNAME       = " + repr(data["gmail"]),
        "MAIL_PASSWORD       = " + repr(data["app_password"]),
        "MAIL_DEFAULT_SENDER = " + repr(data["gmail"]),
        "ADMIN_EMAIL         = " + repr(data["gmail"]),
        "",
        "CHAPTER_NAME        = " + repr(data["chapter_name"]),
        "GRAND_SENECHAL_NAME = " + repr(data["gs_name"]),
    ]
    with open(CFG_PATH, "w", encoding="ascii", errors="replace") as f:
        f.write("\n".join(lines) + "\n")

def create_launcher():
    """Create launcher.bat in the project root."""
    bat = os.path.join(BASE_DIR, "launcher.bat")
    # run.py opens the browser automatically after 1.5s
    content = f'''@echo off
cd /d "{BASE_DIR}"
python run.py
'''
    with open(bat, "w") as f:
        f.write(content)
    return bat


def create_shortcut(bat_path):
    """Create a desktop shortcut using a .vbs script (most reliable on Windows)."""
    # Try standard Desktop first, then OneDrive Desktop
    candidates = [
        os.path.join(os.path.expanduser("~"), "Desktop"),
        os.path.join(os.path.expanduser("~"), "OneDrive", "Desktop"),
        os.path.join(os.path.expanduser("~"), "OneDrive - Personal", "Desktop"),
    ]
    desktop = next((d for d in candidates if os.path.isdir(d)), candidates[0])
    shortcut = os.path.join(desktop, f"{APP_NAME}.lnk")

    # Write a temporary VBScript - more reliable than inline PowerShell
    vbs = os.path.join(BASE_DIR, "_make_shortcut.vbs")
    ico_path = os.path.join(BASE_DIR, "frontend", "static", "img", "chevalier_events.ico").replace("\\", "/")
    vbs_content = f'''Set ws = CreateObject("WScript.Shell")
Set s = ws.CreateShortcut("{shortcut}")
s.TargetPath = "{bat_path}"
s.WorkingDirectory = "{BASE_DIR}"
s.WindowStyle = 1
s.Description = "Launch Chevalier Events"
s.IconLocation = "{ico_path}"
s.Save()
'''
    with open(vbs, "w") as f:
        f.write(vbs_content)

    result = subprocess.run(["cscript", "//Nologo", vbs],
                            capture_output=True, text=True)
    try:
        os.remove(vbs)
    except Exception:
        pass

    if not os.path.exists(shortcut):
        raise RuntimeError(
            f"Could not create Desktop shortcut.\n"
            f"Please create one manually:\n"
            f"Right-click launcher.bat -> Send to -> Desktop (create shortcut)"
        )
    return shortcut



def ensure_admin_can_login():
    """Make sure the admin Person record has can_login=True after setup."""
    try:
        sys.path.insert(0, BASE_DIR)
        from backend import create_app
        app = create_app()
        with app.app_context():
            from backend.models import db, Person
            admins = Person.query.filter_by(is_admin=True).all()
            for p in admins:
                p.can_login = True
            db.session.commit()
    except Exception as e:
        print(f"Note: could not auto-enable admin login: {e}")

